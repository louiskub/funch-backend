export const offers = branches.map((branch, index) => {
  const carType = index === 1 ? carTypes[1] : carTypes[0];
  const [dailyRate, hourlyRate] =
    rates[
      countries.find((country) => country.code === branch.country)!.currency
    ];
  return {
    id: id(4, index + 1),
    branchId: branch.id,
    carTypeId: carType.id,
    currency: countries.find((country) => country.code === branch.country)!
      .currency,
    dailyRate,
    hourlyRate,
  };
});
